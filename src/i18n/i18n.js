// _lang vive en state (roster bridged). El init (storage.getLang + detección de
// navegador) y setLang viven en main.js. Aquí t() lo lee como bare-global → bridge.

// LANGS — lista canónica de idiomas ACTIVOS. Es la ÚNICA fuente para validar un
// código de idioma (init de main.js, guard de setLang). Nota: _I18N puede tener
// más bloques (pt quedó inerte para el futuro) — tener diccionario NO es estar
// activo; validar contra _I18N fue la puerta de atrás por la que un 'pt' zombi
// guardado en localStorage podía reactivarse.
export const LANGS = ['es', 'en'];

export function t(key, params){
  let str = (_I18N[_lang] && _I18N[_lang][key]) || (_I18N['es'][key]) || key;
  if(params) str = str.replace(/\{(\w+)\}/g, (_,k) => params[k] !== undefined ? params[k] : `{${k}}`);
  return str;
}

// locSynopsis(f) — HELPER ÚNICO de sinopsis localizada. Fallback: idioma activo
// (synopsis_en/synopsis_es) → `synopsis` base. Prohibido rehacer este ternario a
// mano en view/controller (lo enforcea validate.py [synopsis-helper]). NO limpia
// marcadores de procedencia (ej. "⚠️ INGLÉS —"): de eso se encarga quien renderiza.
export function locSynopsis(f){
  if(!f) return '';
  if(_lang==='en' && f.synopsis_en) return f.synopsis_en;
  if(_lang==='es' && f.synopsis_es) return f.synopsis_es;
  return f.synopsis || '';
}

export function _applyI18nDOM(){
  // Mecanismo ÚNICO y genérico: TODA string estática del HTML se marca con un
  // atributo data-i18n* y se traduce acá recorriendo el DOM. Cero listas de IDs
  // que mantener — un elemento nuevo se traduce con sólo ponerle el atributo.
  //   data-i18n       → textContent
  //   data-i18n-ph    → placeholder
  //   data-i18n-aria  → aria-label
  //   data-i18n-title → title
  // (auth-btn usa aria + title distintos: los dos atributos conviven en el HTML.)
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    if(el.tagName==='SCRIPT'||el.tagName==='STYLE') return;
    const key=el.getAttribute('data-i18n');
    const val=t(key);
    if(val && val!==key) el.textContent=val;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key=el.getAttribute('data-i18n-ph');
    const val=t(key);
    if(val && val!==key) el.placeholder=val;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    const key=el.getAttribute('data-i18n-aria');
    const val=t(key);
    if(val && val!==key) el.setAttribute('aria-label',val);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{
    const key=el.getAttribute('data-i18n-title');
    const val=t(key);
    if(val && val!==key) el.title=val;
  });
  // Lang toggle — marcar botón activo Y reflejar su bandera en el trigger cerrado.
  // La bandera se sincroniza AQUÍ (no en una función aparte que haya que acordarse
  // de llamar — ese patrón fue la causa del bug de mezcla al arranque): _applyI18nDOM
  // es el único responsable de que TODO el estado visual de idioma sea coherente.
  document.getElementById('lang-btn-es')?.classList.toggle('on', _lang==='es');
  document.getElementById('lang-btn-en')?.classList.toggle('on', _lang==='en');
  const _activeFlag=document.querySelector('#lang-dropdown .lang-opt.on .lang-opt-flag');
  const _trgFlag=document.getElementById('lang-trigger-flag');
  if(_activeFlag && _trgFlag) _trgFlag.textContent=_activeFlag.textContent;
  // dtab labels — los 7 días de la semana son constantes universales
  // Se calculan desde el ISO date del día, sin depender de datos del festival
  const _DOW_ES=['DOM','LUN','MAR','MIÉ','JUE','VIE','SÁB'];
  const _DOW_EN=['SUN','MON','TUE','WED','THU','FRI','SAT'];
  document.querySelectorAll('.dtab[data-day]').forEach(btn=>{
    const dayKey=btn.dataset.day;
    const dateSpan=btn.querySelector('.dtab-date');
    if(!dateSpan||!dayKey) return;
    // Intentar parsear como ISO date (2026-06-03) primero
    const isoMatch=dayKey.match(/^(\d{4})-(\d{2})-(\d{2})$/);
    let lbl='';
    if(isoMatch){
      const dow=new Date(dayKey+'T12:00:00').getDay();
      lbl=_lang==='en'?_DOW_EN[dow]:_DOW_ES[dow];
    } else {
      // Fallback: usar data-lbl-es/en del DOM (formato legado Leviza/FICCI)
      lbl=_lang==='en'?(btn.dataset.lblEn||btn.dataset.lblEs):btn.dataset.lblEs||'';
    }
    if(lbl) dateSpan.textContent=lbl;
  });

}
